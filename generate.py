def zipfile_from_url(url: str) -> zipfile.ZipFile:
    with urllib.request.urlopen(url) as r:
        return zipfile.ZipFile(io.BytesIO(r.read()))

def extract_c_source_from_zip_url(
        dstdir: str,
        url: str,
        include_re: str,
        exclude_re: str|None = None,
        preludes: list[tuple[str, str]]|None = None,
        extra_files: list[tuple[str, str]]|None = None,
        replacements: list[tuple[str, str, str]]|None = None,
    ) -> None:
    pathlib.Path(dstdir).mkdir(parents=True, exist_ok=True)
    with zipfile_from_url(url) as ar:
        names = [n for n in ar.namelist() if re.match(include_re, n)]
        if exclude_re is not None:
            names = [n for n in names if not re.match(exclude_re, n)]
        prel = {}
        if preludes is not None:
            for name in names:
                for p in preludes:
                    if re.match(p[0], name):
                        prel[name] = p[1]
                        break
        repl = {}
        if replacements is not None:
            for name in names:
                for r in replacements:
                    if re.match(r[0], name):
                        if name not in repl:
                            repl[name] = []
                        repl[name].append((r[1], r[2]))
        for name in names:
            with ar.open(name) as f:
                out_path = os.path.join(dstdir, os.path.basename(name))
                with open(out_path, "w") as o:
                    text = f.read().decode("utf-8")
                    if name in repl:
                        for r in repl[name]:
                            text = re.sub(r[0], r[1], text, flags=re.MULTILINE)
                    if name in prel:
                        o.write(prel[name])
                    o.write(text)
        if extra_files is not None:
            for extra in extra_files:
                with open(os.path.join(dstdir, extra[0]), "w") as o:
                    o.write(extra[1])

def snake_to_camel(s: str) -> str:
    res = ""
    upper_next = True
    for c in s:
        if c == "_":
            upper_next = True
        else:
            res += c.upper() if upper_next else c
            upper_next = False
    return res

@dataclass
class Struct:
    name: str
    fields: list['Var']
    def __init__(self, ctx: 'Context', name: str, body: str):
        self.name = name

        # Find fields
        if re.search(r"^#", body, re.MULTILINE):
            raise Exception(f"preprocessor directive in body of struct {name}")
        self.fields = []
        for m in re.finditer(r"^ +(?P<type>\w+( +\*|)) +(?P<name>\w+);", body, re.MULTILINE):
            typ = m["type"].replace(" ", "")
            basetyp = typ.replace("*", "")
            self.fields.append(Var(m["name"], Type(basetyp, ctx.typs[basetyp].gobasetyp, ptrlvl=typ.count("*"))))

@dataclass
class Type:
    # type without pointers or return value
    cbasetyp: str
    gobasetyp: str

    goslicelvl: int = 0
    ptrlvl: int = 0
    func_params: list['Var']|None = None
    func_results: list['Var']|None = None

    def go_str(self) -> str:
        if self.cbasetyp == "void" and self.ptrlvl >= 1:
            return "unsafe.Pointer"
        s = ""
        s += "[]"*self.goslicelvl
        s += "*"*self.ptrlvl
        if self.gobasetyp == "func":
            assert self.func_params is not None
            assert self.func_results is not None
            s += "func("
            for i, p in enumerate(self.func_params):
                if i != 0:
                    s += ", "
                s += p.go_str()
            s += ")"
            if len(self.func_results):
                s += " ("
                for i, p in enumerate(self.func_results):
                    if i != 0:
                        s += ", "
                    s += p.go_str()
                s += ")"
        else:
            s += self.gobasetyp
        return s

    def cgo_str(self) -> str:
        s = ""
        s += "[]"*self.goslicelvl
        s += "*"*self.ptrlvl
        if self.gobasetyp == "func":
            s += "*[0]byte"
        else:
            s += "C."+self.cbasetyp
        return s
    
    def conv_to_go(self, expr: str) -> str:
        if self.cbasetyp == "" and self.gobasetyp == "":
            raise Exception("empty type")
        if self.gobasetyp == "":
            raise Exception(f"cannot convert C-only type {self.cgo_str()} to Go")
        if self.cbasetyp == "":
            # Go-only type
            return expr
        if self.cbasetyp == "cl_bool" and self.ptrlvl == 0:
            return f"({expr} != 0)"
        elif self.cbasetyp == "func":
            return f"unsafe.Pointer({expr})"
        else:
            s = self.go_str()
            if self.ptrlvl > 0:
                s = f"({s})"
            return f"{s}({expr})"
    
    def conv_from_go(self, expr: str) -> str:
        if self.cbasetyp == "" and self.gobasetyp == "":
            raise Exception("empty type")
        if self.cbasetyp == "":
            raise Exception(f"cannot convert Go-only type {self.go_str()} to CGo")
        if self.gobasetyp == "":
            # CGo-only type
            return expr
        if self.cbasetyp == "cl_bool" and self.ptrlvl == 0:
            return f"boolToClBool({expr})"
        elif self.cbasetyp == "void" and self.ptrlvl == 1:
            return expr
        elif self.cbasetyp == "void" and self.ptrlvl == 2:
            return f"(*unsafe.Pointer)({expr})"
        elif self.cbasetyp == "func":
            return f"(*[0]byte)(unsafe.Pointer({expr}))"
        else:
            s = self.cgo_str()
            if self.ptrlvl >= 1:
                s = f"({s})"
            e = expr
            if self.ptrlvl == 2:
                e = f"unsafe.Pointer({e})"
            return f"{s}({e})"


def make_simple_type(cname: str, goname: str|None = None) -> Type:
        if goname is None:
            goname = snake_to_camel(cname.removeprefix("cl_"))
        return Type(cname, goname)

@dataclass
class Var:
    name: str
    typ: Type

    def __init__(self, name: str, typ: Type):
        assert isinstance(name, str)
        assert isinstance(typ, Type)
        self.name = name
        self.typ = typ

    def go_str(self) -> str:
        return self.name + " " + self.typ.go_str()

    def cgo_str(self) -> str:
        return self.name + " " + self.typ.cgo_str()

@dataclass
class Context:
    typs: dict[str, Type]

    def __init__(self):
        self.typs = {}
    
    def add(self, typ: Type):
        self.typs[typ.cbasetyp] = typ

@dataclass
class Enum:
    ctyp: str
    gotyp: str
    values: list[tuple[str, str]]
    def __init__(self, ctyp: str, body: str, gotyp: str):
        self.ctyp = ctyp
        self.gotyp = gotyp
        def fixval(v):
            if gotyp == "bool":
                return {"0": "false", "CL_FALSE": "false",
                        "1": "true", "CL_TRUE": "true"}[v]
            else:
                return v
        self.values = [(m["name"].removeprefix("CL_"), fixval(m["val"])) for m in
            re.finditer(r"^#define +(?P<name>\w+) +(?P<val>.*)$", body, re.MULTILINE)]

@dataclass
class Function:
    name: str
    typ: Type
    api_version: str
    def __init__(self, ctx: Context, name: str, rettyp: str, params: str, api_version: str):
        self.name = name
        self.api_version = api_version
        def parse_params(params):
            res = []
            for m in re.finditer(r"^ *((const )?(?P<typ_unsigned>unsigned )?(?P<typ_base>\w+)(?P<typ_ptrs>( *\*)*) +(?P<name>\w*)(?P<typ_arr>(\[\w*\])*)|(void \(CL_CALLBACK) *\* *(?P<fn_name>\w+)\)\((?P<fn_params>.[^\)]+)\))(,|$)", params, re.MULTILINE):
                if m["name"] is not None:
                    ptrlvl = m["typ_ptrs"].count("*") if m["typ_ptrs"] is not None else 0
                    arr = ""
                    if m["typ_arr"] is not None:
                        arr = m["typ_arr"]
                        ptrlvl += arr.count("[]")
                        arr = arr.replace("[]", "")
                        if arr != "":
                            raise Exception("only VLA supported (not fixed length)")
                    base = m["typ_base"]
                    if m["typ_unsigned"] is not None:
                        if base != "char":
                            raise Exception("only char supported for unsigned types")
                        base = "u"+base
                    res.append(Var(m["name"], Type(base, ctx.typs[base].gobasetyp, ptrlvl=ptrlvl)))
                elif "fn_name" in m.groupdict():
                    res.append(Var(m["fn_name"], Type("func", "func", func_params=parse_params(m["fn_params"]), func_results=[])))
                else:
                    raise Exception(f"expected plain or callback parameter, got {m}")
            return res
        rbtyp = rettyp.replace(" ", "").replace("*", "")
        rptrlvl = rettyp.count("*")
        results = []
        if not(rbtyp == "void" and rptrlvl == 0):
            results.append(Var("_", Type(rbtyp, ctx.typs[rbtyp].gobasetyp, ptrlvl=rptrlvl)))
        self.typ = Type("func", "func",
            func_params=parse_params(params), func_results=results)

@dataclass
class FunctionStepState:
    # Go comment text
    comment: str
    # Go code
    code: str
    # C code
    c_code: str
    # Callback code
    cb_code: str
    # e.g. "E comparable, S ~[]E"
    generic: str
    # List of Go function input parametersd
    in_params: list[Var]
    # List of Go function return parameters
    out_params: list[Var]
    # List of current values in function body
    values: list[Var]
    # List of values to be returned from function
    out_values: list[Var]
    takennames: dict[str,int]
    # Set of values/out_values locked from conversion
    # (these variables will not be converted)
    conv_locks: set[str]

    def __init__(self, in_params: list[Var]):
        assert isinstance(in_params, list)
        for p in in_params: assert isinstance(p, Var)
        self.comment = ""
        self.code = ""
        self.c_code = ""
        self.cb_code = ""
        self.generic = ""
        self.in_params = in_params.copy()
        self.out_params = []
        self.values = in_params.copy()
        self.out_values = []
        self.takennames = {v.name: 0 for v in self.values}
        self.conv_locks = set()

    # Returns the list of in_params variables corresponding to
    # the given names.
    def get_in_params(self, names: list[str]) -> list[Var]:
        p_names = [p.name for p in self.in_params]
        p_idxs = [p_names.index(n) for n in names]
        return [self.in_params[i] for i in p_idxs]

    def get_values(self, names: list[str]) -> list[Var]:
        p_names = [p.name for p in self.values]
        p_idxs = [p_names.index(n) for n in names]
        return [self.values[i] for i in p_idxs]

    # Finds the variables referenced by remove in self.in_params
    # and self.values (must exist).
    #
    # Replaces the self.in_params with fewer new_in_params and
    # replaces all removed self.values with new values.
    #
    # Reassigns names for new values via mkvar. Returns the list of values
    # with actual unique names and new_in_params.
    def replace_in_params(self, remove: list[str], new_in_params: list[Var]) -> tuple[list[Var], list[Var]]:
        p_names = [p.name for p in self.in_params]
        v_names = [p.name for p in self.values]
        p_r_idxs = [p_names.index(n) for n in remove]
        v_r_idxs = [v_names.index(n) for n in remove]
        if len(new_in_params) > len(remove):
            raise Exception("len(new_in_params) must be no more than len(remove)")
        for i in range(len(new_in_params)):
            self.in_params[p_r_idxs[i]] = new_in_params[i]
        p_r_idxs = p_r_idxs[len(new_in_params):]
        p_r_idxs.sort(reverse=True)
        for i in p_r_idxs: self.in_params.pop(i)
        new_values = [Var(name=self.mkvar(self.values[i].name), typ=self.values[i].typ) for i in v_r_idxs]
        for i in range(len(v_r_idxs)): self.values[v_r_idxs[i]] = new_values[i]
        return (new_values, new_in_params)

    def replace_values(self, names: list[str], new_values: list[Var]) -> None:
        if len(names) != len(new_values):
            raise Exception("len(names) must be equal to len(new_values)")
        v_names = [v.name for v in self.values]
        v_idxs = [v_names.index(n) for n in names]
        for i in range(len(v_idxs)):
            self.values[v_idxs[i]] = new_values[i]

    def remove_in_params(self, names: list[str]) -> list[Var]:
        p_names = [v.name for v in self.in_params]
        p_idxs = [p_names.index(n) for n in names]
        ps = [self.in_params[i] for i in p_idxs]
        p_idxs.sort(reverse=True)
        for i in p_idxs: self.in_params.pop(i)
        return ps

    RE_VAR_PREFIX=re.compile(r"^(.*?)(_[0-9]+)?$")
    def mkvar(self, name: str = "v") -> str:
        s = re.sub(self.RE_VAR_PREFIX, r"\1", name)
        if s in self.takennames:
            self.takennames[s] += 1
            s += f"_{self.takennames[s]}"
        self.takennames[s] = 0
        return s
    
    # Raises an exception if a variable is already locked
    # or doesn't exist in values.
    def conv_lock_variables(self, names: list[str]) -> None:
        vnames = [v.name for v in self.values]
        for name in names:
            if name not in vnames:
                raise Exception(f"variable {name} not in values")
            self.conv_locks.add(name)

    # Raises an exception if a variable is not locked
    # or doesn't exist in values.
    def conv_unlock_variables(self, names: list[str]) -> None:
        vnames = [v.name for v in self.values]
        for name in names:
            if name not in vnames:
                raise Exception(f"variable {name} not in values")
            if name not in self.conv_locks:
                raise Exception(f"variable {name} not locked")
            self.conv_locks.remove(name)

# Single segment of binding code.
class FunctionStep:
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        pass

@dataclass
class FunctionStepConvToC(FunctionStep):
    values_field: Literal["values", "out_values"]
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        new_values = []
        for i, param in enumerate(getattr(s, self.values_field)):
            assert isinstance(param, Var)
            if (param.typ.gobasetyp == "" or # Already CGo-only type
                  param.name in s.conv_locks # Locked from conversion
                ):
                new_values.append(param)
                continue
            if param.typ.cbasetyp == "func":
                assert param.typ.func_params is not None
                assert param.typ.func_results is not None
                cb_name = f"go_cl_callback_{func.name}"
                s.c_code += f"extern void {cb_name}("
                for j, p in enumerate(param.typ.func_params):
                    if j != 0:
                        s.c_code += ", "
                    s.c_code += f"{p.typ.cbasetyp}{"*"*p.typ.ptrlvl}"
                s.c_code += ");\n"
                s.cb_code += f"//export {cb_name}\n"
                s.cb_code += f"func {cb_name}("
                for j, p in enumerate(param.typ.func_params):
                    if j != 0:
                        s.cb_code += ", "
                    s.cb_code += p.cgo_str()
                s.cb_code += ") {\n"
                param.typ.func_params = [x for x in param.typ.func_params if x.name != "user_data"]
                step_st = FunctionStepState(param.typ.func_params)
                steps = [FunctionStepConvToGo("values")]
                for step in steps:
                    step(step_st, ctx, func)
                s.cb_code += textwrap.indent(step_st.code, "\t")
                s.cb_code += "\tuid := int(uintptr(unsafe.Pointer(user_data)))\n"
                # TODO: Not every function should be unregistered after a single call.
                # Maybe we can receive whether to unregister through the callback info
                # somehow.
                s.cb_code += "\tdefer callbackUnregister(uid)\n"
                s.cb_code += f"\t(callbackFn(uid).({param.typ.go_str()}))("
                for j, p in enumerate(step_st.values):
                    if j != 0:
                        s.cb_code += ", "
                    s.cb_code += p.name
                s.cb_code += ")\n"
                s.cb_code += "}\n"
                s.code += "var callback_uid unsafe.Pointer\n"
                s.code += "var callback *[0]byte\n"
                s.code += f"if {param.name} != nil {{\n"
                s.code += f"\tcallback_uid = unsafe.Pointer(uintptr(callbackRegister({param.name})))\n"
                s.code += f"\tcallback = (*[0]byte)(C.{cb_name})\n"
                s.code += "}\n"
                new_values.append(Var("callback", param.typ))
            elif param.name == "user_data":
                s.in_params = [x for x in s.in_params if x.name != "user_data"]
                new_values.append(Var("callback_uid", param.typ))
            else:
                name = s.mkvar(param.name)
                s.code += f"{name} := {param.typ.conv_from_go(param.name)}\n"
                new_values.append(Var(name, param.typ))
        setattr(s, self.values_field, new_values)

@dataclass
class FunctionStepConvToGo(FunctionStep):
    values_field: Literal["values", "out_values"]
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        new_values = []
        for i, param in enumerate(getattr(s, self.values_field)):
            if (param.typ.cbasetyp == "" or # Already Go-only type
                  param.name in s.conv_locks # Locked from conversion
                ):
                new_values.append(param)
                continue
            name = s.mkvar(param.name)
            s.code += f"{name} := {param.typ.conv_to_go(param.name)}\n"
            new_values.append(Var(name, param.typ))
        setattr(s, self.values_field, new_values)

