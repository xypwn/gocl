# clGetXXXInfo functions
@dataclass
class FunctionStepGetInfo(FunctionStep):
    kind: Literal["pre_conv", "post_conv"]
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        if not re.match(GET_INFO_FUNC_NAME_RE, func.name):
            return
        if self.kind == "pre_conv":
            s.conv_lock_variables(["param_name", "param_value_size", "param_value", "param_value_size_ret"])
        else:
            s.conv_unlock_variables(["param_name", "param_value_size", "param_value", "param_value_size_ret"])
            s.comment += f"// Simplified binding for {func.name}.\n//\n"
            s.comment += "// value must be a pointer to the result variable.\n"
            s.comment += "// The result variable must be typed according to param_name.\n"
            s.comment += "// The Go types allowed for the C types are:\n"
            s.comment += "//\t- numerical/struct (e.g. cl_uint, size_t, cl_device_type): equivalent Go type (e.g. uint32, uint64, DeviceType)\n"
            s.comment += "//\t- string (e.g. char[]): Go string or []byte (either is accepted)\n"
            s.comment += "//\t- array (e.g. size_t[]): slice of equivalent Go type (e.g. []uint64)\n"

            s.code += f"var pin runtime.Pinner\n"
            s.code += f"defer pin.Unpin()\n"

            nactsize = s.mkvar(f"param_actual_size")
            s.code += f"var {nactsize} C.size_t\n"

            ([vrval, vsize, vsize_ret], [vval]) = s.replace_in_params(
                ["param_value", "param_value_size", "param_value_size_ret"],
                [Var("param_value", Type("", "any"))])

            [vname] = s.get_values(["param_name"])
            s.replace_values(["param_name"],
                [Var(f"{vname.typ.conv_from_go(vname.name)}", vname.typ)])

            s.code += f"{vrval.name} := reflect.ValueOf({vval.name})\n"
            s.code += f"if {vrval.name}.Kind() != reflect.Pointer {{\n\tpanic(\"expected param_value to be pointer to value, but got \"+{vrval.name}.Kind().String())\n}}\n"

            s.code += f"isString := {vrval.name}.Elem().Kind() == reflect.String\n"
            s.code += f"if isString || {vrval.name}.Elem().Kind() == reflect.Slice {{\n"
            s.code += f"\t{vrval.name} = {vrval.name}.Elem() // need to take the address of the slice, not the pointer\n"

            # Call function with nil params to determine actual size
            s.code += f"\tC.{func.name}("
            for i, v in enumerate(s.values):
                if i != 0:
                    s.code += ", "
                if v.name == vsize.name:
                    s.code += "0"
                elif v.name == vrval.name:
                    s.code += "nil"
                elif v.name == vsize_ret.name:
                    s.code += f"&{nactsize}"
                else:
                    s.code += v.name
            s.code += ")\n"

            s.code += f"\tvar elemTyp reflect.Type\n"
            s.code += f"\tif isString {{ elemTyp = reflect.TypeFor[byte]() }} else {{ elemTyp = {vrval.name}.Type().Elem() }}\n"
            s.code += f"\tsliceLen := int({nactsize})/int(elemTyp.Size())\n"
            s.code += f"\tnewSlice := reflect.MakeSlice(reflect.SliceOf(elemTyp), sliceLen, sliceLen)\n"
            s.code += f"\tif isString {{\n"
            s.code += f"\t\toutVal := {vrval.name}\n"
            s.code += f"\t\t{vrval.name} = newSlice\n"
            s.code += f"\t\tdefer func() {{ outVal.Set({vrval.name}.Convert(reflect.TypeFor[string]())) }}()\n"
            s.code += "\t} else {\n"
            s.code += f"\t\t{vrval.name}.Set(newSlice)\n"
            s.code += "\t}\n"
            s.code += f"}} else {{\n\t{nactsize} = C.size_t({vrval.name}.Type().Size())\n}}\n"
            s.code += f"pin.Pin({vrval.name}.UnsafePointer())\n"
            vrval.name = f"{vrval.name}.UnsafePointer()"
            vsize.name = f"{nactsize}"
            vsize_ret.name = f"&{nactsize}"


class FunctionStepCall(FunctionStep):
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        assert func.typ.func_params is not None
        assert func.typ.func_results is not None
        params = func.typ.func_params
        results = func.typ.func_results
        returns_err = (not "errcode_ret" in [p.name for p in params] and
            len(results) == 1 and results[0].typ.cbasetyp == "cl_int")
        if len(results) > 0:
            assert len(results) == 1
            retname = s.mkvar("res")
            s.code += f"{retname} := "
        s.code += f"C.{func.name}("
        for i, v in enumerate(s.values):
            if i != 0:
                s.code += ", "
            s.code += v.name
        s.code += ")\n"
        s.values = []
        if len(results) > 0:
            if returns_err:
                s.out_params.append(Var("_err", Type("", "error")))
                s.out_values.append(Var(f"makeError(ErrorCode({retname}))", Type("", "error")))
            else:
                s.out_params.insert(0, Var("_res", results[0].typ))
                s.out_values.insert(0, Var(retname, s.out_params[0].typ))

@dataclass
class ResultHint:
    param: str
    kind: Literal["normal", "error"] = "normal"

RESULT_HINTS: dict[str, list[ResultHint]] = {
    r"\w+": [ResultHint("errcode_ret", kind="error")],
    r"clGetDeviceAndHostTimer": [ResultHint("device_timestamp"), ResultHint("host_timestamp")],
    r"clGetHostTimer": [ResultHint("host_timestamp")],
}

# Turns function results passed as pointers in the C API into
# results in the Go API.
#
# Parameters returned as slices are handled in FunctionStepSlice.
class FunctionStepParamResults(FunctionStep):
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        hints = [h for [pat, hs] in RESULT_HINTS.items() for h in hs if re.fullmatch(pat, func.name)]
        for hint in hints:
            in_names = [p.name for p in s.in_params]
            v_names = [p.name for p in s.values]
            if hint.param not in in_names:
                continue
            ip = in_names.index(hint.param)
            iv = v_names.index(hint.param)
            vres = s.mkvar(f"{hint.param}")
            btyp = s.in_params[ip].typ.cbasetyp
            s.code += f"var {vres} {Type(btyp, "").cgo_str()}\n"
            s.values[iv] = Var(f"&{vres}", Type(btyp, "", ptrlvl=1))
            if hint.kind == "error":
                otyp = Type("", "error")
                s.out_values.append(Var(f"makeError(ErrorCode({vres}))", otyp))
                s.out_params.append(Var(f"_{hint.param}", otyp))
            else:
                otyp = ctx.typs[btyp]
                s.out_values.append(Var(f"{vres}", otyp))
                s.out_params.append(Var(f"_{hint.param}", otyp))
            s.in_params.pop(ip)

class FunctionStepRet(FunctionStep):
    def __call__(self, s: FunctionStepState, ctx: Context, func: Function):
        if len(s.out_values) == 0:
            return
        s.code += "return "
        for i, param in enumerate(s.out_values):
            if i != 0:
                s.code += ", "
            s.code += param.name
        s.code += "\n"
        s.out_values = []

@dataclass
class CustomFuncs:
    go: dict[str, list[str]]
    c: dict[str, list[str]]
    extra: list[str]

def get_custom_funcs(filename: str) -> CustomFuncs:
    with open(filename) as f:
        s = f.read()
    BINDFN_RE = r"((?P<comment>(^\/\/.*$\n)+))?^\/\/(?P<bind>bind(c|)):(?P<name>\w+)$\n^(?P<fn>func .*\n(^(?!\}).*\n)+\}|extern .+;$)$"
    res = CustomFuncs({}, {}, [])
    for m in re.finditer(BINDFN_RE, s, re.MULTILINE):
        s = m["fn"]
        if m["comment"] is not None:
            s = m["comment"] + s
        if m["name"] == "extra":
            res.extra.append(s)
            continue
        if m["name"] not in res.c: res.c[m["name"]] = []
        if m["name"] not in res.go: res.go[m["name"]] = []
        d = res.go if m["bind"] == "bind" else res.c
        d[m["name"]].append(s)
    return res

def generate_bindings(dstdir: str, go_prelude: str, headers: list[str], custom_funcs: CustomFuncs) -> None:
    with open(os.path.join(dstdir, "doc.go"), "w") as o:
        o.write("// Package cl contains OpenCL functions.\npackage cl")
    with open(os.path.join(dstdir, "cl.go"), "w") as o, open(os.path.join(dstdir, "cl_go_defs.h"), "w") as o_c:
        ctx = Context()

        ctx.add(make_simple_type("char", "int8"))
        ctx.add(make_simple_type("uchar", "uint8"))
        ctx.add(make_simple_type("size_t", "uint64"))
        ctx.add(make_simple_type("cl_bool", "bool"))
        ctx.add(make_simple_type("cl_char", "int8"))
        ctx.add(make_simple_type("cl_uchar", "uint8"))
        ctx.add(make_simple_type("cl_short", "int16"))
        ctx.add(make_simple_type("cl_ushort", "uint16"))
        ctx.add(make_simple_type("cl_int", "int32"))
        ctx.add(make_simple_type("cl_uint", "uint32"))
        ctx.add(make_simple_type("cl_long", "int64"))
        ctx.add(make_simple_type("cl_ulong", "uint64"))
        ctx.add(make_simple_type("cl_half", "float16.Float16"))
        ctx.add(make_simple_type("cl_float", "float32"))
        ctx.add(make_simple_type("cl_double", "float64"))
        ctx.add(make_simple_type("void", "void"))

        def docs_url(typ: str) -> str:
            return f"https://registry.khronos.org/OpenCL/specs/unified/refpages/man/html/{typ}.html"

        o.write(go_prelude)
        for header in headers:
            o.write(f"// BEGIN {header} //\n\n")
            hdr = ""
            with open(header) as f:
                hdr = f.read()

            o.write("// Typedefs\n\n")
            typedefs = [m["name"] for m in
                re.finditer(r"^typedef [^\n{}]+ (?P<name>cl_[a-z0-9_]+);", hdr, re.MULTILINE)]
            for name in typedefs:
                if name in ctx.typs:
                    continue
                ctx.add(make_simple_type(name))
                o.write(f"// See {docs_url(name)}\n")
                o.write(f"type {ctx.typs[name].go_str()} {ctx.typs[name].cgo_str()}\n")
            o.write("\n")

            o.write("// Structs\n\n")
            structs = [Struct(ctx, m["name"], m["body"]) for m in
                re.finditer(r"^typedef struct[^{\n]*\{(?P<body>(\n[ #][^\n]+)+\n)\} *(?P<name>cl_\w+);", hdr, re.MULTILINE)]
            for struct in structs:
                name = struct.name
                ctx.add(make_simple_type(name))
                o.write(f"// See {docs_url(name)}\n")
                o.write(f"type {ctx.typs[name].go_str()} {ctx.typs[name].cgo_str()}\n")
                for field in struct.fields:
                    fname = snake_to_camel(field.name)
                    o.write(f"func (s *{ctx.typs[name].go_str()}) {fname}() {field.typ.go_str()} {{")
                    o.write(f" return {field.typ.conv_to_go(f"s.{field.name}")} ")
                    o.write(f"}}\n")
                    o.write(f"func (s *{ctx.typs[name].go_str()}) Set{fname}(v {field.typ.go_str()}) {{")
                    o.write(f" s.{field.name} = {field.typ.conv_from_go("v")} ")
                    o.write(f"}}\n")
            o.write("\n")

            if os.path.basename(header) == "cl.h":
                o.write("// Enums\n\n")
                enums = []
                err_codes = re.search(r"^\/\* Error Codes \*\/\n(?P<body>(.+\n\n?)+)", hdr, re.MULTILINE)
                assert err_codes is not None
                enums.append(Enum(
                        "int",
                        err_codes["body"],
                        gotyp="ErrorCode",
                    ))
                for m in re.finditer(r"^\/\* (?P<type>cl_\w+)( and (?P<type2>cl_\w+))?( - bitfield)? \*\/\n(?P<body>([^\n].*\n)+)", hdr, re.MULTILINE):
                    ctyp = m["type"]
                    gotyp = ""
                    if ctyp in ctx.typs:
                        gotyp = ctx.typs[ctyp].go_str()
                    else:
                        gotyp = snake_to_camel(ctyp.removeprefix("cl_"))
                    enums.append(Enum(ctyp, m["body"], gotyp))
                for enum in enums:
                    o.write(f"// See {docs_url("enums")}\n")
                    o.write(f"const ( // {enum.gotyp}\n")
                    for value in enum.values:
                        o.write(f"\t{value[0]} {enum.gotyp} = {value[1]}\n")
                    o.write(f")\n")

                for enum in enums:
                    if enum.ctyp in ("cl_version", "cl_bool"):
                        continue
                    o.write(f"func (v {enum.gotyp}) String() string {{\n")
                    if enum.ctyp.endswith("_flags"):
                        o.write(f"\tvar s strings.Builder\n")
                        for value in enum.values:
                            if "/* deprecated */" in value[1]:
                                # Some enum values have been renamed with the
                                # old name marked as deprecated; we want to avoid
                                # duplicates
                                continue
                            o.write(f"\tif v&{value[0]} != 0 {{ if s.Len() != 0 {{ s.WriteByte('|') }}; s.WriteString(\"{value[0]}\") }}\n")
                        o.write(f"\treturn s.String()\n")
                    else:
                        o.write("\tswitch v {\n")
                        for value in enum.values:
                            if "/* deprecated */" in value[1]:
                                # Some enum values have been renamed with the
                                # old name marked as deprecated; we want to avoid
                                # duplicates
                                continue
                            o.write(f"\tcase {value[0]}: return \"{value[0]}\"\n")
                        o.write(f"\tdefault: return fmt.Sprintf(\"UNKNOWN (%d)\", v)\n")
                        o.write(f"\t}}\n")
                    o.write(f"}}\n")
                o.write("\n")

                o.write("// Functions\n\n")
                funcs = [Function(ctx, m["name"], m["type"], m["params"], m["api_version"]) for m in
                    re.finditer(r"^extern CL_API_ENTRY (CL_API_PREFIX__\w+ )?(?P<type>[\w \*]+) CL_API_CALL\n(?P<name>cl\w+)\((?P<params>(.+,\n)*.+)\) CL_API_SUFFIX__(?P<api_version>\w+);", hdr, re.MULTILINE)]
                for func in funcs:
                    if func.name == "clEnqueueNativeKernel":
                        # TODO This function handles callbacks a bit strangely
                        continue
                    
                    if func.name in custom_funcs.go:
                        for f in custom_funcs.c[func.name]:
                            o_c.write(f)
                            o_c.write("\n")
                        for f in custom_funcs.go[func.name][:-1]:
                            o.write(f)
                            o.write("\n")
                        o.write(f"// See {docs_url(func.name)}\n")
                        o.write(custom_funcs.go[func.name][-1])
                        o.write("\n")
                        continue

                    steps = [
                        FunctionStepParamResults(),
                        FunctionStepSlice("pre_conv"),
                        FunctionStepGetInfo("pre_conv"),
                        FunctionStepConvToC("values"),
                        FunctionStepSlice("post_conv"),
                        FunctionStepGetInfo("post_conv"),
                        FunctionStepCall(),
                        FunctionStepConvToGo("out_values"),
                        FunctionStepRet(),
                    ]
                    assert func.typ.func_params is not None
                    assert func.typ.func_results is not None
                    step_st = FunctionStepState(func.typ.func_params)
                    for step in steps:
                        step(step_st, ctx, func)

                    o_c.write(step_st.c_code)
                    o.write(step_st.cb_code)

                    goname = func.name.removeprefix("cl")
                    if step_st.comment != "":
                        o.write(f"{step_st.comment}//\n")
                    o.write(f"// See {docs_url(func.name)}\n")
                    o.write(f"func {goname}")
                    if step_st.generic != "":
                        o.write(f"[{step_st.generic}]")
                    o.write("(")
                    for i, param in enumerate(step_st.in_params):
                        if i != 0:
                            o.write(", ")
                        o.write(param.go_str())
                    o.write(") ")
                    if len(step_st.out_params):
                        o.write("(")
                        for i, param in enumerate(step_st.out_params):
                            if i != 0:
                                o.write(", ")
                            o.write(param.go_str())
                        o.write(") ")
                    o.write("{\n")
                    o.write(textwrap.indent(step_st.code, "\t"))
                    o.write("}\n")
                for func in custom_funcs.extra:
                    o.write("// (CUSTOM)\n")
                    o.write(func)
                    o.write("\n")
                o.write("\n")


            o.write(f"// END {header} //\n\n")

